"""Deduplication Engine for Seeds and Entities."""

import Levenshtein
from enum import StrEnum
from dataclasses import dataclass
from typing import Optional

class DedupResult(StrEnum):
    SAME = "SAME"
    PROBABLY_SAME = "PROBABLY_SAME"
    UNKNOWN = "UNKNOWN"
    DIFFERENT = "DIFFERENT"

@dataclass
class DedupProfile:
    normalized_title: str
    text_content: str
    brand: str | None = None
    model_sku: str | None = None
    image_hash: str | None = None

class DedupEngine:
    @staticmethod
    def compare(a: DedupProfile, b: DedupProfile) -> DedupResult:
        """Compare two profiles using V1 deduplication heuristics."""
        # 1. Exact SKU/Model match is a very strong signal
        if a.model_sku and b.model_sku:
            if a.model_sku.lower() == b.model_sku.lower():
                return DedupResult.SAME
                
        # 2. Image hash comparison (Hamming distance)
        # Assuming hex strings generated by imagehash
        if a.image_hash and b.image_hash:
            try:
                dist = bin(int(a.image_hash, 16) ^ int(b.image_hash, 16)).count('1')
                if dist == 0:
                    return DedupResult.SAME
                elif dist <= 5:
                    return DedupResult.PROBABLY_SAME
                # If image hashes are very different, they might just be different photos of the same thing
            except Exception:
                pass
                
        # 3. Title Levenshtein Distance
        if a.normalized_title and b.normalized_title:
            dist = Levenshtein.distance(a.normalized_title, b.normalized_title)
            max_len = max(len(a.normalized_title), len(b.normalized_title))
            if max_len > 0:
                ratio = (max_len - dist) / max_len
                if ratio > 0.95:
                    return DedupResult.SAME
                elif ratio > 0.80:
                    return DedupResult.PROBABLY_SAME
                elif ratio < 0.40:
                    return DedupResult.DIFFERENT
                    
        return DedupResult.UNKNOWN
